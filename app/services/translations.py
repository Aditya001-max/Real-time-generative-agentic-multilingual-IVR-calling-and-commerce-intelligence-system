def t(prompt_id: str, lang: str = DEFAULT_LANGUAGE) -> str:
    """Look up a prompt translation. Falls back to English if missing."""
    table = PROMPTS.get(prompt_id, {})
    return table.get(lang) or table.get(DEFAULT_LANGUAGE) or ""


def all_prompt_strings_for(lang: str) -> list[str]:
    """All translated prompt strings for one language — used by TTS pre-warm."""
    return [PROMPTS[pid].get(lang, PROMPTS[pid][DEFAULT_LANGUAGE]) for pid in PROMPTS]


